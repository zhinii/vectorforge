let language = 'en';
export function getLanguage() { return language; }
export function setLanguage(value) {
  // Unknown values fall back to English; only these two codes cross the API.
  language = value === 'zh' || value === 'zh-CN' || value === 'zh-Hans' ? 'zh' : 'en';
  return language;
}
function interpolate(text, params) {
  return text.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(params, key) ? String(params[key]) : match);
}
export function t(keyOrEnglish, params = {}) {
  const key = String(keyOrEnglish ?? '');
  if (Object.hasOwn(catalogs[language], key)) return interpolate(catalogs[language][key], params);
  if (language === 'en') return interpolate(key, params);
  // Translate only bounded, known generated UI messages. Unknown text remains
  // untouched, so identifiers, arbitrary model replies, and user text survive.
  let match;
  if ((match = /^Connected to (.+)\. Describe a design, or use the drawing tools\.$/.exec(key))) return t('connection.ready', { model: match[1] });
  if ((match = /^Connected to (.+)$/.exec(key))) return t('connection.connected', { model: match[1] });
  if (key.startsWith('Connection test failed. ')) return t('Connection test failed. ') + t(key.slice(24));
  if ((match = /^(e\d+): (length|radius|width|height|angle|chord|size)$/.exec(key))) return t('dimension.title', { id: match[1], dimension: t(match[2]) });
  if ((match = /^(e\d+) (length|radius|width|height|chord|size) = ([-+\d.eE]+) mm$/.exec(key))) return `${match[1]} ${t(match[2])} = ${match[3]} 毫米`;
  if ((match = /^Font size ([-+\d.eE]+) mm$/.exec(key))) return `字号 ${match[1]} 毫米`;
  if ((match = /^text “([^\r\n]{1,240})” size ([-+\d.eE]+) at \(([-+\d.eE, ]+)\)$/.exec(key))) return `文字“${match[1]}” 字号 ${match[2]}，位置 (${match[3]})`;
  if ((match = /^Chord ([-+\d.eE]+) mm$/.exec(key))) return `弦长 ${match[1]} 毫米`;
  if ((match = /^(?:R)([-+\d.eE]+)$/.exec(key))) return `半径 ${match[1]} 毫米`;
  if (/^[-+\d.eE, ]+ mm$/.test(key)) return key.replace(/ mm$/, ' 毫米');
  if ((match = /^move (e\d+) → \(([-+\d.eE, ]+)\)$/.exec(key))) return `移动 ${match[1]} → (${match[2]})`;
  if ((match = /^delete (e\d+)$/.exec(key))) return `删除 ${match[1]}`;
  if ((match = /^(line|circle|arc|rect|polygon|star|bezier|Bézier) ([-+\d.eER°→×(), ]+|\d+ (?:sides|points) R[-+\d.eE]+|R[-+\d.eE]+ at \([-+\d.eE, ]+\))$/.exec(key))) {
    return t(match[1]) + ' ' + match[2].replace(' sides ', ' 边 ').replace(' points ', ' 角 ').replace(' at ', '，中心 ');
  }
  return interpolate(key, params);
}

export function applyTranslations(root = globalThis.document) {
  if (!root) return;
  if (root.documentElement) root.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.getAttribute('data-i18n'));
  }
  for (const attribute of ['title', 'aria-label', 'placeholder']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    }
  }
  const toggle = root.getElementById?.('language-toggle');
  if (toggle) {
    toggle.textContent = language === 'en' ? '中文' : 'English';
    toggle.setAttribute('lang', language === 'en' ? 'zh-CN' : 'en');
    toggle.setAttribute('aria-label', language === 'en' ? 'Switch to Chinese' : '切换为英文');
    toggle.setAttribute('title', language === 'en' ? 'Switch to Chinese' : '切换为英文');
  }
}
